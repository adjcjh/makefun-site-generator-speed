// Fast re-implementation of makefun-site 1.0.0's build, written from scratch.
// run(input) returns exactly the output tree makefun-site returns for the
// same input: pages, index/tag pages, build-report.txt and static files.
// Strategy: cache slugify results, escape HTML in bulk instead of per
// character, lex+render Markdown in one pass with char-code classification,
// and compile each template once into a small JS function that appends to an
// output array (no node-tree walk or scope-chain walk per render).

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const hasOwn = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/;
const ESC_RE_G = /[&<>"']/g;
export function escapeHtml(text) {
  // Most strings hold no escapable character: one test, no replace.
  return ESC_RE.test(text) ? text.replace(ESC_RE_G, (c) => ESCAPES[c]) : text;
}

const slugCache = new Map();
export function slugify(text) {
  let out = slugCache.get(text);
  if (out !== undefined) return out;
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let s = '';
  let gap = false;
  for (const ch of plain) {
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = s.length > 0;
      continue;
    }
    if (gap) s += '-';
    gap = false;
    s += keep;
  }
  s = s.slice(0, 64).replace(/-+$/, '');
  out = s === '' ? 'untitled' : s;
  slugCache.set(text, out);
  return out;
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function longDate(date) {
  const y = date.slice(0, 4);
  const m = Number(date.slice(5, 7));
  const d = Number(date.slice(8, 10));
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];
const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME_RE = /^[a-z0-9-]+$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG_RE = /^[^"[\]]+$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw[0] === '"') {
    if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw[0] === '[') return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE_RE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG_RE.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME_RE.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG_RE.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

// Parse one key/value line: returns [key, raw] or null when the line is not
// "key: value" (key of a-z and _, colon, one space, then the value).
function keyValue(line) {
  let i = 0;
  while (i < line.length) {
    const c = line[i];
    if ((c >= 'a' && c <= 'z') || c === '_') i++;
    else break;
  }
  if (i === 0 || line[i] !== ':') return null;
  if (i + 1 === line.length) return [line.slice(0, i), ''];
  if (line[i + 1] !== ' ') return null;
  return [line.slice(0, i), line.slice(i + 2)];
}

function parseFrontMatter(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') { close = i; break; }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (line === '') continue;
    let blank = true;
    for (let k = 0; k < line.length; k++) {
      const c = line[k];
      if (c !== ' ' && c !== '\t') { blank = false; break; }
    }
    if (blank || line[0] === '#') continue;
    const kv = keyValue(line);
    if (kv === null) return { error: `line ${i + 1} is not "key: value"` };
    const key = kv[0];
    const raw = kv[1].replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!hasOwn(data, 'title')) return { error: 'no title' };
  return { data, body: lines.slice(close + 1).join('\n') };
}

// ---------------------------------------------------------------- Markdown

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

// Fence opener: returns the language, or null. Fence closer: boolean.
function fenceLang(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return null;
  let i = 3;
  while (i < line.length) {
    const c = line[i];
    if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-') i++;
    else break;
  }
  for (let j = i; j < line.length; j++) {
    const c = line[j];
    if (c !== ' ' && c !== '\t') return null;
  }
  return line.slice(3, i);
}
function isFenceClose(line) {
  if (line[0] !== '`' || line[1] !== '`' || line[2] !== '`') return false;
  for (let j = 3; j < line.length; j++) {
    const c = line[j];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

// Heading: [depth, text] or null. Text has leading spaces/tabs after the
// #'s and trailing spaces/tabs dropped; empty text is not a heading.
function headingOf(line) {
  let n = 0;
  while (n < line.length && line[n] === '#') n++;
  if (n === 0 || n > 6) return null;
  const c = line[n];
  if (c !== ' ' && c !== '\t') return null;
  let a = n;
  while (a < line.length && (line[a] === ' ' || line[a] === '\t')) a++;
  let b = line.length;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  if (b === a) return null;
  return [n, line.slice(a, b)];
}

function isHr(line) {
  if (line[0] !== '-' && line[0] !== '*') return false;
  const mark = line[0];
  if (line[1] !== mark || line[2] !== mark) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line[j];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

// Trim spaces/tabs at both ends (a paragraph/quote/list line as rendered).
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

function endsParagraph(line) {
  const c = line[0];
  if (c === undefined) return true;
  if (c === ' ' || c === '\t') return isBlank(line);
  if (c === '`') return fenceLang(line) !== null;
  if (c === '#') return headingOf(line) !== null;
  if (c === '-' || c === '*') return isHr(line);
  return false;
}

// Ordered list marker: [number, rest] or null (1-9 digits, ". ", rest).
function orderedOf(line) {
  let i = 0;
  while (i < line.length && line[i] >= '0' && line[i] <= '9') i++;
  if (i === 0 || i > 9) return null;
  if (line[i] !== '.' || line[i + 1] !== ' ') return null;
  return [Number(line.slice(0, i)), line.slice(i + 2)];
}

function isContinued(line) {
  return line[0] === ' ' && line[1] === ' ' && line.length > 2 && !/\s/.test(line[2]);
}

function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (c !== '*') continue;
    if (s[j + 1] === '*') { j++; continue; }
    return j;
  }
  return -1;
}

const INLINE_SPECIAL_RE = /[\\`*[]/;
function inline(s, env) {
  // Fast path: no backslash, backtick, star or bracket at all — the whole
  // string is plain text, escaped in one pass.
  if (!INLINE_SPECIAL_RE.test(s)) return escapeHtml(s);
  let out = '';
  let i = 0;
  const n = s.length;
  while (i < n) {
    // Bulk-copy the run up to the next inline-special character.
    let j = n;
    const a = s.indexOf('\\', i);
    if (a !== -1 && a < j) j = a;
    const b = s.indexOf('`', i);
    if (b !== -1 && b < j) j = b;
    const c2 = s.indexOf('*', i);
    if (c2 !== -1 && c2 < j) j = c2;
    const d = s.indexOf('[', i);
    if (d !== -1 && d < j) j = d;
    if (j > i) {
      out += escapeHtml(s.slice(i, j));
      i = j;
      if (i >= n) break;
    }
    const c = s[i];
    if (c === '\\' && i + 1 < n && ESCAPABLE.has(s[i + 1])) {
      out += escapeHtml(s[i + 1]);
      i += 2;
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', i + 1);
      if (k > i + 1) {
        out += `<code>${escapeHtml(s.slice(i + 1, k))}</code>`;
        i = k + 1;
      } else {
        out += '`';
        i++;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const k = findUnescaped(s, '**', i + 2);
        if (k > i + 2) {
          out += `<strong>${inline(s.slice(i + 2, k), env)}</strong>`;
          i = k + 2;
        } else {
          out += '**';
          i += 2;
        }
        continue;
      }
      const k = findSingleStar(s, i + 1);
      if (k > i + 1) {
        out += `<em>${inline(s.slice(i + 1, k), env)}</em>`;
        i = k + 1;
      } else {
        out += '*';
        i++;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1);
      const m = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        out += `<a href="${escapeHtml(env.link(target))}">${inline(s.slice(i + 1, k), env)}</a>`;
        i = m + 1;
        continue;
      }
      out += '[';
      i++;
      continue;
    }
    out += escapeHtml(c);
    i++;
  }
  return out;
}

// Render Markdown in one pass over its lines (no token array).
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const blocks = [];
  const toc = [];
  const ids = new Set();
  let excerpt = null;
  let i = 0;
  const L = lines.length;
  while (i < L) {
    const line = lines[i];
    const c0 = line[0];
    // Dispatch on the first character: every block kind is fixed by it,
    // and a space/tab lead can only be a blank line or a paragraph line.
    if (c0 === undefined) { i++; continue; } // blank line
    if (c0 === '`') {
      const lang = fenceLang(line);
      if (lang !== null) {
        const body = [];
        i++;
        while (i < L && !isFenceClose(lines[i])) body.push(lines[i++]);
        i++;
        const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
        let code = '';
        for (let k = 0; k < body.length; k++) code += `${escapeHtml(body[k])}\n`;
        blocks.push(`<pre><code${cls}>${code}</code></pre>\n`);
        continue;
      }
    } else if (c0 === '#') {
      const h = headingOf(line);
      if (h !== null) {
        const id = uniqueSlug(slugify(h[1]), ids);
        const html = inline(h[1], env);
        blocks.push(`<h${h[0]} id="${id}">${html}</h${h[0]}>\n`);
        if (h[0] === 2 || h[0] === 3) toc.push({ level: h[0], id, html });
        i++;
        continue;
      }
    } else if (c0 === '-' || c0 === '*') {
      if (isHr(line)) { blocks.push('<hr>\n'); i++; continue; }
    } else if (c0 === '>') {
      const body = [];
      while (i < L && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l[1] === ' ' ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (let k = 0; k < body.length; k++) {
        const t = trimLine(body[k]);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>\n`);
      continue;
    } else if (c0 === ' ' || c0 === '\t') {
      if (isBlank(line)) { i++; continue; }
    }
    const bullet = (c0 === '-' || c0 === '*') && line[1] === ' ';
    const ordered = bullet ? null : (c0 >= '0' && c0 <= '9' ? orderedOf(line) : null);
    if (bullet || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      let start = 1;
      if (isOrdered) start = ordered[0];
      while (i < L) {
        const l = lines[i];
        if (isOrdered) {
          const m = orderedOf(l);
          if (m !== null) { items.push([trimLine(m[1])]); i++; continue; }
        } else if ((l[0] === '-' || l[0] === '*') && l[1] === ' ') {
          items.push([trimLine(l.slice(2))]); i++; continue;
        }
        if (isContinued(l)) { items[items.length - 1].push(trimLine(l)); i++; continue; }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let inner = '';
      for (let k = 0; k < items.length; k++) inner += `<li>${inline(items[k].join('\n'), env)}</li>\n`;
      blocks.push(`${open}\n${inner}</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < L && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '' };
}

// ---------------------------------------------------------------- templates

class TemplateError extends Error {}

const PATH_RE = /^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$/;
const FOR_RE = /^for ([A-Za-z_][A-Za-z0-9_]*) in (\S+)$/;
const IF_RE = /^if (not )?(\S+)$/;
const INCLUDE_RE = /^include "([a-z0-9-]+)"$/;

function pathOf(name, text) {
  if (!PATH_RE.test(text)) throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
  return text.split('.');
}

function tokenize(name, src) {
  const tokens = [];
  let text = '';
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open === -1 || open === src.length - 1) {
      text += src.slice(i);
      break;
    }
    const next = src[open + 1];
    if (next !== '{' && next !== '%') {
      text += src.slice(i, open + 1);
      i = open + 1;
      continue;
    }
    text += src.slice(i, open);
    if (next === '{') {
      const raw = src[open + 2] === '{';
      const close = src.indexOf(raw ? '}}}' : '}}', open + (raw ? 3 : 2));
      if (close === -1) throw new TemplateError(`template "${name}": a ${raw ? '{{{' : '{{'} is not closed`);
      if (text !== '') tokens.push({ t: 'text', text });
      text = '';
      tokens.push({ t: raw ? 'raw' : 'var', path: pathOf(name, src.slice(open + (raw ? 3 : 2), close).trim()) });
      i = close + (raw ? 3 : 2);
      continue;
    }
    const close = src.indexOf('%}', open + 2);
    if (close === -1) throw new TemplateError(`template "${name}": a {% is not closed`);
    const end = close + 2;
    const lineStart = src.lastIndexOf('\n', open - 1) + 1;
    const nl = src.indexOf('\n', end);
    const lineEnd = nl === -1 ? src.length : nl;
    const standalone = /^[ \t]*$/.test(src.slice(lineStart, open)) && /^[ \t]*$/.test(src.slice(end, lineEnd));
    if (standalone) text = text.slice(0, text.length - (open - lineStart));
    if (text !== '') tokens.push({ t: 'text', text });
    text = '';
    tokens.push({ t: 'tag', tag: src.slice(open + 2, close).trim() });
    i = standalone ? (nl === -1 ? src.length : nl + 1) : end;
  }
  if (text !== '') tokens.push({ t: 'text', text });
  return tokens;
}

function parseTemplate(name, src) {
  const root = { kind: 'root', body: [] };
  const stack = [root];
  let body = root.body;
  for (const tok of tokenize(name, src)) {
    if (tok.t === 'text') body.push({ kind: 'text', text: tok.text });
    else if (tok.t === 'var' || tok.t === 'raw') body.push({ kind: tok.t, path: tok.path });
    else {
      const tag = tok.tag;
      const top = stack[stack.length - 1];
      let m;
      if ((m = FOR_RE.exec(tag)) !== null) {
        const node = { kind: 'for', name: m[1], path: pathOf(name, m[2]), body: [] };
        body.push(node);
        stack.push(node);
        body = node.body;
      } else if ((m = IF_RE.exec(tag)) !== null) {
        const node = { kind: 'if', not: m[1] !== undefined, path: pathOf(name, m[2]), then: [], else: null };
        body.push(node);
        stack.push(node);
        body = node.then;
      } else if (tag === 'else') {
        if (top.kind !== 'if' || top.else !== null) throw new TemplateError(`template "${name}": an else outside an if`);
        top.else = [];
        body = top.else;
      } else if (tag === 'endfor' || tag === 'endif') {
        if (top.kind !== (tag === 'endfor' ? 'for' : 'if')) throw new TemplateError(`template "${name}": an ${tag} with no open ${tag.slice(3)}`);
        stack.pop();
        const parent = stack[stack.length - 1];
        body = parent.kind === 'root' ? parent.body : parent.kind === 'for' ? parent.body : parent.else ?? parent.then;
      } else if ((m = INCLUDE_RE.exec(tag)) !== null) body.push({ kind: 'include', name: m[1] });
      else throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
    }
  }
  if (stack.length > 1) throw new TemplateError(`template "${name}": a ${stack[stack.length - 1].kind} is not closed`);
  return root.body;
}

// `lk` reads the first name of a path from the scope stack, innermost
// first. Scope values are never undefined and never functions, so a defined
// non-function value is an own property; inherited function-valued names
// (toString, ...) are skipped with a hasOwn check.
function lk(sc, first) {
  for (let i = sc.length - 1; i >= 0; i--) {
    const fr = sc[i];
    const v = fr[first];
    if (v !== undefined) {
      if (typeof v === 'function' && !hasOwn(fr, first)) continue;
      return v;
    }
  }
  return undefined;
}
function textOf(v) {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.map(textOf).join(', ');
  return '';
}
function truthy(v) {
  if (Array.isArray(v)) return v.length > 0;
  return v !== undefined && v !== null && v !== false && v !== '' && v !== 0;
}
const H = { esc: escapeHtml, txt: textOf, tr: truthy, lk, ho: hasOwn };

// Compile a parsed template into a function (sc, d, o, H, T) that appends
// its output to the array o. sc is the scope stack (innermost last), d the
// include depth, T a Map of name -> compiled function. Compiled templates
// are cached by source text: the compiled function never depends on the
// template's name (only a parse error's message does, and failures are not
// cached).
const templateCache = new Map();
function compileTemplate(name, src) {
  const hit = templateCache.get(src);
  if (hit !== undefined) return hit;
  const nodes = parseTemplate(name, src);
  let ctr = 0;
  const code = [];
  // Emit code that resolves `path` into temp variable `_v<n>` (undefined
  // when any step is missing).
  function pathCode(path) {
    const v = `_v${ctr++}`;
    code.push(`var ${v}=H.lk(sc,${JSON.stringify(path[0])});`);
    for (let k = 1; k < path.length; k++) {
      code.push(`${v}=(${v}!==null&&typeof ${v}==='object'&&H.ho(${v},${JSON.stringify(path[k])}))?${v}[${JSON.stringify(path[k])}]:undefined;`);
    }
    return v;
  }
  function gen(list) {
    for (const n of list) {
      if (n.kind === 'text') {
        code.push(`o.push(${JSON.stringify(n.text)});`);
      } else if (n.kind === 'var') {
        const v = pathCode(n.path);
        code.push(`o.push(H.esc(H.txt(${v})));`);
      } else if (n.kind === 'raw') {
        const v = pathCode(n.path);
        code.push(`o.push(H.txt(${v}));`);
      } else if (n.kind === 'if') {
        const v = pathCode(n.path);
        code.push(`if(H.tr(${v})!==${n.not}){`);
        gen(n.then);
        if (n.else !== null) {
          code.push('}else{');
          gen(n.else);
        }
        code.push('}');
      } else if (n.kind === 'for') {
        const a = `_a${ctr++}`;
        const k = `_k${ctr++}`;
        const v = pathCode(n.path);
        code.push(`var ${a}=${v};if(Array.isArray(${a})){for(var ${k}=0;${k}<${a}.length;${k}++){sc.push({[${JSON.stringify(n.name)}]:${a}[${k}],loop:{index:${k}+1,first:${k}===0,last:${k}===${a}.length-1,length:${a}.length}});`);
        gen(n.body);
        code.push('sc.pop();}}');
      } else if (n.kind === 'include') {
        const f = `_f${ctr++}`;
        code.push(`if(d<8){var ${f}=T.get(${JSON.stringify(n.name)});if(${f}!==undefined)${f}(sc,d+1,o,H,T);}`);
      }
    }
  }
  gen(nodes);
  const fn = new Function('sc', 'd', 'o', 'H', 'T', code.join('\n'));
  templateCache.set(src, fn);
  return fn;
}

